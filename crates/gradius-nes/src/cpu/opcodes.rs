//! The opcode table: `execute` routes each opcode to its family.
//!
//! Split out of the single `execute` match in `cpu.rs`; the arms are the
//! same code, grouped by what the instruction does.

use super::Bus;
use super::Cpu;

mod alu;
mod control;
mod memory;
mod undocumented;

impl Cpu {
    pub(super) fn execute(&mut self, opcode: u8, bus: &mut impl Bus) -> u32 {
        match opcode {
            0x00 | 0x20 | 0x60 | 0x40 | 0x4C | 0x6C | 0x10 | 0x30 => self.control(opcode, bus),
            0x50 | 0x70 | 0x90 | 0xB0 | 0xD0 | 0xF0 | 0x18 | 0x38 => self.control(opcode, bus),
            0x58 | 0x78 | 0xB8 | 0xD8 | 0xF8 | 0x48 | 0x08 | 0x68 => self.control(opcode, bus),
            0x28 | 0xEA | 0x1A | 0x3A | 0x5A | 0x7A | 0xDA | 0xFA => self.control(opcode, bus),
            0xA9 | 0xA5 | 0xB5 | 0xAD | 0xBD | 0xB9 | 0xA1 | 0xB1 => self.memory(opcode, bus),
            0xA2 | 0xA6 | 0xB6 | 0xAE | 0xBE | 0xA0 | 0xA4 | 0xB4 => self.memory(opcode, bus),
            0xAC | 0xBC | 0x85 | 0x95 | 0x8D | 0x9D | 0x99 | 0x81 => self.memory(opcode, bus),
            0x91 | 0x86 | 0x96 | 0x8E | 0x84 | 0x94 | 0x8C | 0x24 => self.memory(opcode, bus),
            0x2C => self.memory(opcode, bus),
            0x69 | 0x65 | 0x75 | 0x6D | 0x7D | 0x79 | 0x61 | 0x71 => self.alu(opcode, bus),
            0xE9 | 0xEB | 0xE5 | 0xF5 | 0xED | 0xFD | 0xF9 | 0xE1 => self.alu(opcode, bus),
            0xF1 | 0x29 | 0x25 | 0x35 | 0x2D | 0x3D | 0x39 | 0x21 => self.alu(opcode, bus),
            0x31 | 0x09 | 0x05 | 0x15 | 0x0D | 0x1D | 0x19 | 0x01 => self.alu(opcode, bus),
            0x11 | 0x49 | 0x45 | 0x55 | 0x4D | 0x5D | 0x59 | 0x41 => self.alu(opcode, bus),
            0x51 | 0xC9 | 0xC5 | 0xD5 | 0xCD | 0xDD | 0xD9 | 0xC1 => self.alu(opcode, bus),
            0xD1 | 0xE0 | 0xE4 | 0xEC | 0xC0 | 0xC4 | 0xCC | 0x0A => self.alu(opcode, bus),
            0x06 | 0x16 | 0x0E | 0x1E | 0x4A | 0x46 | 0x56 | 0x4E => self.alu(opcode, bus),
            0x5E | 0x2A | 0x26 | 0x36 | 0x2E | 0x3E | 0x6A | 0x66 => self.alu(opcode, bus),
            0x76 | 0x6E | 0x7E | 0xE6 | 0xF6 | 0xEE | 0xFE | 0xC6 => self.alu(opcode, bus),
            0xD6 | 0xCE | 0xDE | 0xE8 | 0xC8 | 0xCA | 0x88 | 0xAA => self.alu(opcode, bus),
            0x8A | 0xA8 | 0x98 | 0xBA | 0x9A => self.alu(opcode, bus),
            _ => self.undocumented(opcode, bus),
        }
    }

    /// Records an opcode no arm claims instead of panicking.
    fn record_unknown_opcode(&mut self, opcode: u8) -> u32 {
        self.unknown_opcode.get_or_insert(opcode);
        self.unknown_opcode_count = self.unknown_opcode_count.saturating_add(1);
        2
    }
}
